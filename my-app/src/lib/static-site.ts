/**
 * The static marketing site (butwalhacks.com on Cloudflare Workers static
 * assets) versus the app (app.butwalhacks.com on Vercel). docs/CLOUDFLARE.md.
 *
 * Single source for:
 *   - which URL paths belong to the app (auth, dashboards, API, and pages
 *     whose content users edit and expect to see change immediately);
 *   - which route directories scripts/build-static.mjs leaves out of the
 *     static export;
 *   - the `_redirects` and `_headers` files the static site ships with;
 *   - src/proxy.ts, so the app host keeps serving these paths instead of
 *     bouncing them back to the marketing host.
 */
import { buildStaticCsp, CSP_REPORT_GROUP, CSP_REPORT_PATH } from "./csp";
import { TRANSPORT_HEADERS } from "./security-headers";
import { SITE_REDIRECTS } from "./site-redirects";
import { isAppMaintenance, MAINTENANCE_PATH } from "./app-maintenance";

export { isAppMaintenance } from "./app-maintenance";

export const DEFAULT_APP_ORIGIN = "https://app.butwalhacks.com";

/** Whole sections owned by the app: `/x` and everything under it. */
export const APP_PREFIXES = [
  "/api",
  "/auth",
  "/dashboard",
  "/portal",
  "/orgs",
  "/claim",
  "/sign-in",
  "/account-exists",
  "/calendar",
  // User-edited pages: profiles, sponsor pages, trust-marker checks and
  // embeddable profile widgets. Rendered by the app so edits show at once.
  "/p",
  "/sponsor",
  "/verify",
  "/widget",
  "/projects/impact",
  // Teams shows each signed-in member their pending invites, and nowhere
  // else does, so the whole section stays on the app.
  "/teams",
  // Reads its view from the query string (?view=report&year=), which a
  // static export cannot render, so it stays on the app.
  "/transparency",
] as const;

/** Single-segment detail pages owned by the app; their list pages are static. */
export const APP_DETAIL_PARENTS = ["/projects"] as const;

/** True when `pathname` is served by the app, not the static site. */
export function isAppPath(pathname: string): boolean {
  if (APP_PREFIXES.some((p) => pathname === p || pathname.startsWith(`${p}/`))) return true;
  return APP_DETAIL_PARENTS.some((parent) => {
    if (!pathname.startsWith(`${parent}/`)) return false;
    const rest = pathname.slice(parent.length + 1);
    return rest.length > 0 && !rest.includes("/");
  });
}

/**
 * Route directories (under src/app) that the static export leaves out. Must
 * cover every app path above, plus anything that cannot be exported.
 */
export const STATIC_EXCLUDED_ROUTE_DIRS = [
  "api",
  "(auth)",
  "calendar",
  "p",
  "verify",
  "widget",
  "(main)/dashboard",
  "(main)/portal",
  "(main)/orgs",
  "(main)/account-exists",
  "(main)/sponsor",
  "(main)/projects/impact",
  "(main)/projects/[id]",
  "(main)/teams",
  "(main)/transparency",
] as const;

/**
 * `_redirects` for the static site. Consolidation redirects first (308, as
 * Next sends them), then every app path to the app origin: 307 for /api so
 * a POST stays a POST, 302 elsewhere so a later move back is not stuck in
 * browser caches. Query strings pass through.
 *
 * During app maintenance (lib/app-maintenance.ts) app paths are not sent to
 * the app at all: each one serves the "Under maintenance" page in place
 * (a 200 rewrite, so the URL stays as the visitor typed it).
 */
export function staticRedirectsFile(
  appOrigin = DEFAULT_APP_ORIGIN,
  options: { maintenance?: boolean } = {},
): string {
  const maintenance = options.maintenance ?? isAppMaintenance();
  const lines: string[] = ["# Generated by scripts/build-static.mjs from src/lib/static-site.ts"];
  for (const r of SITE_REDIRECTS) lines.push(`${r.source} ${r.destination} 308`);
  if (maintenance) lines.push("# App under maintenance (lib/app-maintenance.ts): app paths show the notice.");
  for (const prefix of APP_PREFIXES) {
    if (maintenance) {
      lines.push(`${prefix} ${MAINTENANCE_PATH} 200`);
      lines.push(`${prefix}/* ${MAINTENANCE_PATH} 200`);
      continue;
    }
    const code = prefix === "/api" ? 307 : 302;
    lines.push(`${prefix} ${appOrigin}${prefix} ${code}`);
    lines.push(`${prefix}/* ${appOrigin}${prefix}/:splat ${code}`);
  }
  for (const parent of APP_DETAIL_PARENTS) {
    lines.push(maintenance ? `${parent}/:id ${MAINTENANCE_PATH} 200` : `${parent}/:id ${appOrigin}${parent}/:id 302`);
  }
  return `${lines.join("\n")}\n`;
}

/**
 * The page CSP for the static site: same policy as the app's static pages,
 * except violation reports go to the app (the static site has no API) and
 * forms may post to the app.
 */
export function staticSiteCsp(appOrigin = DEFAULT_APP_ORIGIN): string {
  return buildStaticCsp(false)
    .replace(`report-uri ${CSP_REPORT_PATH}`, `report-uri ${appOrigin}${CSP_REPORT_PATH}`)
    .replace("form-action 'self'", `form-action 'self' ${appOrigin}`);
}

/**
 * `_headers` for the static site: the app's transport headers and CSP on
 * every response, immutable caching for hashed build assets, and noindex on
 * previews so a workers.dev copy never competes with the real site.
 */
export function staticHeadersFile(options: { appOrigin?: string; noindex?: boolean } = {}): string {
  const appOrigin = options.appOrigin ?? DEFAULT_APP_ORIGIN;
  const all = [
    ...TRANSPORT_HEADERS,
    { key: "Content-Security-Policy", value: staticSiteCsp(appOrigin) },
    { key: "Permissions-Policy", value: "camera=(self), microphone=(), geolocation=()" },
    { key: "Reporting-Endpoints", value: `${CSP_REPORT_GROUP}="${appOrigin}${CSP_REPORT_PATH}"` },
    ...(options.noindex ? [{ key: "X-Robots-Tag", value: "noindex" }] : []),
  ];
  const lines = ["# Generated by scripts/build-static.mjs from src/lib/static-site.ts", "/*"];
  for (const h of all) lines.push(`  ${h.key}: ${h.value}`);
  lines.push("", "/_next/static/*", "  Cache-Control: public, max-age=31536000, immutable");
  return `${lines.join("\n")}\n`;
}
